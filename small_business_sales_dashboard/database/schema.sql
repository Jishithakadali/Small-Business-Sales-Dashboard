-- Run this SQL in the Supabase SQL Editor for the MVP starter.
-- This starter uses the server-side service-role key only in Express.
-- Never place that key in frontend JavaScript or commit it to GitHub.

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(trim(name)) between 1 and 100),
  price numeric(12, 2) not null check (price > 0),
  created_at timestamptz not null default now()
);

create table if not exists public.sales (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(id) on delete restrict,
  quantity integer not null check (quantity > 0),
  total numeric(12, 2) not null check (total >= 0),
  created_at timestamptz not null default now()
);

-- Keep Row Level Security enabled. This application accesses the database
-- from Express using a server-side service-role key, which bypasses RLS.
-- Do not expose that key to browsers. Before adding public client access or
-- deploying, design authenticated-user policies appropriate to the app.
alter table public.products enable row level security;
alter table public.sales enable row level security;
